import assert from 'node:assert/strict';
import {Group,Mesh,BoxGeometry,MeshStandardMaterial,ShaderLib,Vector3} from 'three';
import {RobotCutaway} from '../public/robot-cutaway.js';
const material=new MeshStandardMaterial(),root=new Group();
root.add(new Mesh(new BoxGeometry(),material),new Mesh(new BoxGeometry(),material));
let calls=0;material.onBeforeCompile=shader=>{calls++;shader.uniforms.existing={value:1};};
material.customProgramCacheKey=()=> 'existing';
const cutaway=new RobotCutaway();cutaway.apply(root);cutaway.apply(root);
const shader={...ShaderLib.standard,uniforms:{}};material.onBeforeCompile(shader,{});
assert.equal(calls,1,'A batched/shared material is patched once and retains its lighting hook');
assert(shader.uniforms.existing);assert(shader.vertexShader.includes('instanceMatrix*cutawayPosition'));
assert.equal(material.customProgramCacheKey(),'existing|robot-cutaway-v1');
assert.equal(material.transparent,false,'Cutaway never makes an entire export batch transparent');
assert.equal(material.depthWrite,true,'Unaffected station surfaces still occlude normally');
const eye=new Vector3(0,1,4),target=new Vector3(0,1,0);
cutaway.update(eye,target,true,1/60);
assert(cutaway.uniforms.robotCutawayAmount.value>0&&cutaway.uniforms.robotCutawayAmount.value<1);
eye.x=9;assert.equal(cutaway.uniforms.robotCutawayEye.value.x,0,'The view is captured by value');
for(let i=0;i<60;i++)cutaway.update(eye,target,true,1/60);
assert.equal(cutaway.uniforms.robotCutawayAmount.value,1);
cutaway.update(eye,target,false,1/60);assert(cutaway.uniforms.robotCutawayAmount.value<1);
cutaway.clear();assert.equal(cutaway.uniforms.robotCutawayAmount.value,0,'Fly, overview and ball views restore the complete station immediately');
console.log('PASS localized cutaway material chaining, instancing, depth, fade and reset');
