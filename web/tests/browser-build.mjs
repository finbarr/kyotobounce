import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,stat,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {buildCollisionPack} from '../../tools/browser-collision.mjs';
import {decodeCollisionPack} from '../public/physics/collision-pack.js';
const directory=await mkdtemp(join(tmpdir(),'kyoto-collision-build-'));
try{
 const output=join(directory,'collision.bin'),layout={schemaVersion:1,units:'meters',spawn:{x:0,y:1,z:0},boxes:[],panels:[],beams:[],flights:[],escalators:[]},source=JSON.stringify(layout);
 const receipt=await buildCollisionPack(source,{output}),bytes=await readFile(output),before=await stat(output,{bigint:true});
 assert.equal(decodeCollisionPack(bytes).layoutSha256,receipt.layoutSha256);
 assert.deepEqual(await buildCollisionPack(source,{output}),receipt);
 assert.equal((await stat(output,{bigint:true})).mtimeNs,before.mtimeNs,'An unchanged build must reuse its verified collision file');
 const corrupt=Buffer.from(bytes);corrupt[corrupt.length-1]^=1;await writeFile(output,corrupt);
 await buildCollisionPack(source,{output});assert.deepEqual(await readFile(output),bytes,'Corrupt generated bytes must be rebuilt');
 await writeFile(output+'.json',JSON.stringify({...receipt,compilerSha256:'outdated'}));
 assert.equal((await buildCollisionPack(source,{output})).compilerSha256,receipt.compilerSha256);
 await writeFile(output+'.json','incomplete');await buildCollisionPack(source,{output});
 const changed=await buildCollisionPack(JSON.stringify({...layout,spawn:{x:2,y:1,z:0}}),{output});
 assert.notEqual(changed.layoutSha256,receipt.layoutSha256);assert.notEqual(changed.sha256,receipt.sha256);
 assert.equal(decodeCollisionPack(await readFile(output)).spawn.x,2);
 console.log('PASS collision build reuse, corruption recovery, interrupted receipt and source/compiler invalidation');
}finally{await rm(directory,{recursive:true,force:true});}
